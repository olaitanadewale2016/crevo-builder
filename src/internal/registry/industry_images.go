// SearchCuratedIndustryImages searches the expanded multi-industry catalog using token-based relevance scoring
func SearchCuratedIndustryImages(category, imageType, mood, tone string, limit int) []ImageEntry {
	if limit <= 0 {
		limit = 10
	}

	rawQuery := strings.ToLower(strings.TrimSpace(category))
	tokens := strings.FieldsFunc(rawQuery, func(r rune) bool {
		return r == ' ' || r == ',' || r == '/' || r == '_'
	})

	type scoredEntry struct {
		entry ImageEntry
		score int
	}

	var scored []scoredEntry

	for _, img := range AllCuratedIndustryImages {
		if imageType != "" && img.Type != imageType {
			continue
		}
		if mood != "" && img.Mood != mood {
			continue
		}
		if tone != "" && img.Tone != tone {
			continue
		}

		if len(tokens) == 0 {
			scored = append(scored, scoredEntry{entry: img, score: 10})
			continue
		}

		score := 0
		catLower := strings.ToLower(img.Category)
		subjLower := strings.ToLower(img.Subject)

		for _, tok := range tokens {
			if len(tok) <= 1 {
				continue
			}
			if catLower == tok {
				score += 30
			} else if strings.Contains(catLower, tok) || strings.Contains(tok, catLower) {
				score += 18
			}

			for _, c := range img.Categories {
				cl := strings.ToLower(c)
				if cl == tok {
					score += 28
					break
				} else if strings.Contains(cl, tok) || strings.Contains(tok, cl) {
					score += 15
				}
			}

			if strings.Contains(subjLower, tok) {
				score += 20
			}
		}

		if score > 0 {
			scored = append(scored, scoredEntry{entry: img, score: score})
		}
	}

	sort.SliceStable(scored, func(i, j int) bool {
		return scored[i].score > scored[j].score
	})

	var results []ImageEntry
	for _, s := range scored {
		results = append(results, s.entry)
		if len(results) >= limit {
			break
		}
	}

	return results
}
